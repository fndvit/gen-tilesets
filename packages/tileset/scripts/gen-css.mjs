/**
 * Writes `src/render/css.generated.ts` from `src/render/tileset.css`, and stamps
 * the sentinel hash into both.
 *
 *   node scripts/gen-css.mjs           # write
 *   node scripts/gen-css.mjs --check   # exit 1 if either file is stale
 *
 * **Why a generated module rather than reading the file at runtime.** The
 * renderer injects its CSS into whatever document or shadow root it mounts in
 * (`styles.ts`), and a `?raw` import or a `fetch` would tie that to one bundler
 * or to a served URL. A string constant works under every bundler and none.
 *
 * **Why it is committed.** The workspace consumes the package's source with no
 * build step (`CLAUDE.md`), so the module has to exist in `src`. `--check` is
 * what `styles.test.ts` runs, so a forgotten regeneration is a red test rather
 * than a published stylesheet that disagrees with its own `TILESET_CSS`.
 *
 * **The sentinel.** `tileset.css` declares `--gen-tilesets: v<hash>` on the box,
 * where the hash is FNV-1a over the minified rules with that value zeroed. So the
 * value names exactly these rules, and `injectStyles` can tell "these rules
 * already reach this box" from "some version of them does". The script writes
 * the hash back into the source file, because the bundled and linked copies are
 * that file and have to carry it too.
 *
 * The minifier is deliberately small: strip comments, collapse whitespace, drop
 * it beside the punctuation that never needs it. It keeps a space *before* `:`
 * and between selectors, because both are meaningful in a selector (`a :hover`,
 * `a img`); a space after `:` never is.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("../src/render/tileset.css", import.meta.url));
const out = fileURLToPath(new URL("../src/render/css.generated.ts", import.meta.url));

const SENTINEL = /(--gen-tilesets:\s*)v[0-9a-f]{8}/;
const ZERO = "v00000000";

const minify = (css) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{};,>])\s*/g, "$1")
    .replace(/:\s+/g, ":")
    .replace(/;}/g, "}")
    .trim();

function fnv1a(text) {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}

// Line endings are normalised so a CRLF checkout (no `.gitattributes` here)
// neither hashes differently nor reads as stale.
const lf = (text) => text.replace(/\r\n/g, "\n");

const source = lf(readFileSync(src, "utf8"));
if (!SENTINEL.test(source)) {
  console.error("tileset.css has no `--gen-tilesets: v<8 hex>` declaration.");
  process.exit(1);
}
const zeroed = source.replace(SENTINEL, `$1${ZERO}`);
const hash = `v${fnv1a(minify(zeroed))}`;
const stamped = zeroed.replace(SENTINEL, `$1${hash}`);

const module =
  "// Generated by `scripts/gen-css.mjs` from `tileset.css`. Do not edit; run `pnpm css`.\n" +
  `export const TILESET_CSS = ${JSON.stringify(minify(stamped))};\n` +
  `export const TILESET_HASH = ${JSON.stringify(hash)};\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = lf(readFileSync(out, "utf8"));
  } catch {}
  if (current !== module || source !== stamped) {
    console.error("tileset.css or css.generated.ts is stale: run `pnpm --filter @fndvit/gen-tilesets css`.");
    process.exit(1);
  }
} else {
  if (source !== stamped) writeFileSync(src, stamped);
  writeFileSync(out, module);
}
